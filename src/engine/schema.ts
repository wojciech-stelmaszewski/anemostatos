export const getIn = (obj: unknown, path: string): unknown =>
  path.split('.').reduce<unknown>((o, k) => (o as Record<string, unknown>)?.[k], obj);

export function setIn<T>(obj: T, path: string, value: unknown): T {
  const [head, ...rest] = path.split('.');
  const o = obj as Record<string, unknown>;
  const next = rest.length ? setIn(o[head!], rest.join('.'), value) : value;
  if (Array.isArray(obj)) {
    const copy = [...obj];
    copy[Number(head)] = next;
    return copy as T;
  }
  return { ...o, [head!]: next } as T;
}
